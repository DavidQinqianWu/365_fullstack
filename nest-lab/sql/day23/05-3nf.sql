-- Day 23 · 05:第三范式(3NF)—— 非主键列不能「间接」依赖主键
-- tasks_2nf 里:task_id → owner_email → owner_name。owner_name 是通过 owner_email 间接确定的 → 负责人拆成 users 表
-- 顺便把「标签」也当成一个实体(tags 表):任务和标签是多对多,中间靠 task_tags 这张对照表
-- REFERENCES(外键)今天只用来「写明关系」:这一列指向哪张表的哪一行。它会拦住什么、删除时怎么办,Day 24 讲
SET search_path = day23;
DROP TABLE IF EXISTS task_tags, checklist_items, tasks, tags, users;

CREATE TABLE users (
  id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,   -- 让数据库发号(Day 24 比较各种发号方式)
  email text,
  name  text
);
CREATE TABLE tasks (
  id       integer PRIMARY KEY,                -- 沿用宽表里的任务编号
  title    text,
  done     boolean,
  owner_id integer REFERENCES users (id)       -- 1:N:一个用户有多个任务,一个任务只有一个负责人
);
CREATE TABLE checklist_items (
  task_id  integer REFERENCES tasks (id),      -- 1:N:一个任务有多个清单项
  position integer,
  text     text,
  done     boolean,
  PRIMARY KEY (task_id, position)
);
CREATE TABLE tags (
  id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text
);
CREATE TABLE task_tags (                       -- N:M 的中间表(对照表):一行 = 「这个任务贴了这个标签」
  task_id integer REFERENCES tasks (id),
  tag_id  integer REFERENCES tags (id),
  PRIMARY KEY (task_id, tag_id)
);

-- 搬数据:先搬「被指向」的表(users、tags),再搬指向它们的表
INSERT INTO users (email, name)
SELECT DISTINCT owner_email, owner_name FROM tasks_2nf ORDER BY owner_email;

INSERT INTO tasks (id, title, done, owner_id)
SELECT t.task_id, t.title, t.done, u.id
FROM tasks_2nf t
JOIN users u ON u.email = t.owner_email;     -- 按邮箱找到对应的用户编号(JOIN 的细节 Day 25 讲)

INSERT INTO checklist_items SELECT * FROM checklist_items_1nf;

INSERT INTO tags (name)
SELECT DISTINCT tag FROM task_tags_2nf ORDER BY tag;

INSERT INTO task_tags (task_id, tag_id)
SELECT tt.task_id, g.id
FROM task_tags_2nf tt
JOIN tags g ON g.name = tt.tag;

SELECT * FROM users ORDER BY id;
SELECT * FROM tasks ORDER BY id;
SELECT * FROM tags ORDER BY id;
SELECT * FROM task_tags ORDER BY task_id, tag_id;

