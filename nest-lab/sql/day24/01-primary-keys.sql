-- Day 24 · 01:主键怎么发号 —— serial / IDENTITY ALWAYS / IDENTITY BY DEFAULT
-- 今天的表都在独立的 schema day24 里;重跑本文件会把 day24 整个删掉重建。
DROP SCHEMA IF EXISTS day24 CASCADE;
CREATE SCHEMA day24;
SET search_path = day24;

-- ① serial:旧写法。其实是「建一个序列 + 把列默认值设成 nextval(序列)」的简写
CREATE TABLE t_serial (id serial PRIMARY KEY, name text);
\d t_serial
SELECT pg_get_serial_sequence('t_serial', 'id') AS 背后的序列;

-- ② GENERATED ALWAYS AS IDENTITY:SQL 标准写法;id 只能由数据库发
CREATE TABLE t_always (id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY, name text);
INSERT INTO t_always (name) VALUES ('a'), ('b');
INSERT INTO t_always (id, name) VALUES (100, '手写的 id');          -- 被拒绝
SELECT * FROM t_always ORDER BY id;

-- ③ GENERATED BY DEFAULT AS IDENTITY:允许手写 id,但序列不知道你手写过
CREATE TABLE t_by_default (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text);
INSERT INTO t_by_default (id, name) VALUES (1, '手写了 1'), (2, '手写了 2');
INSERT INTO t_by_default (name) VALUES ('数据库发号');             -- 序列从 1 开始发 → 撞车
INSERT INTO t_by_default (name) VALUES ('再试一次');               -- 这次拿到 2,还是撞车
INSERT INTO t_by_default (name) VALUES ('第三次');                 -- 3,终于成功
SELECT * FROM t_by_default ORDER BY id;
-- serial 的行为和 BY DEFAULT 一样:手写 id 不会被拒绝,同样会撞车
INSERT INTO t_serial (id, name) VALUES (1, '手写了 1');
INSERT INTO t_serial (name) VALUES ('数据库发号');

-- ④ 回滚之后,用掉的号不会还回去(Day 22 留下的钩子)
INSERT INTO t_always (name) VALUES ('c');
BEGIN;
INSERT INTO t_always (name) VALUES ('会被回滚');
ROLLBACK;
INSERT INTO t_always (name) VALUES ('d');
SELECT * FROM t_always ORDER BY id;     -- 中间缺了一个号
