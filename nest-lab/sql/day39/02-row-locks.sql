--   B: INSERT INTO transfers (account_id, amount) VALUES (1, 10);   -- 卡住:FOR UPDATE 和 FOR KEY SHARE 冲突
--   A: ROLLBACK;
--
-- 四种行锁的冲突关系(× = 冲突要等):
--                      FOR KEY SHARE   FOR SHARE   FOR NO KEY UPDATE   FOR UPDATE
--   FOR KEY SHARE                                                        ×
--   FOR SHARE                                          ×                 ×
--   FOR NO KEY UPDATE                     ×            ×                 ×
--   FOR UPDATE              ×             ×            ×                 ×
-- (以官方文档「Explicit Locking → Row-Level Locks」为准)
